//! 스토리/스테이지 데이터. 로직과 분리해 두었으므로 텍스트만 고쳐도 시나리오를 바꿀 수 있다.
//! Line = (화자, 대사). 화자가 ""이면 지문. "{name}"은 플레이어 이름으로 치환된다.
//! (조사 결합을 피하려고 "{name}" 바로 뒤에는 조사를 붙이지 않는다.)

pub type Line = (&'static str, &'static str);

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EMove {
    /// 일반 공격
    Strike,
    /// 예고된 강공격 (방어 권장)
    Heavy,
    /// 약한 공격 + 주력 강탈
    Drain,
    /// 다음에 받는 피해 절반
    Barrier,
    /// 약한 공격 + 공격력 감소 저주
    Hex,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SpotResult {
    Weakness,
    HealCharm,
    CeCharm,
    Ambush,
    Lore,
}

pub struct Spot {
    pub label: &'static str,
    pub result: SpotResult,
    pub text: &'static [Line],
}

pub struct EnemySpec {
    pub name: &'static str,
    pub grade: &'static str,
    pub hp: i32,
    pub atk: i32,
    pub def: i32,
    pub pattern: &'static [EMove],
}

pub struct StageData {
    pub chapter: &'static str,
    pub title: &'static str,
    pub place: &'static str,
    pub intro: &'static [Line],
    pub intro_sorcerer: &'static [Line],
    pub intro_curse: &'static [Line],
    pub spots: [Spot; 3],
    pub enemy: EnemySpec,
    pub entrance: &'static [Line],
    pub victory: &'static [Line],
    pub purify_label: &'static str,
    pub absorb_label: &'static str,
    pub purify_text: &'static [Line],
    pub absorb_text: &'static [Line],
}

